# prompt_builder.py

import json

def build_module_prompt(tech_task, manifest, module, interfaces, all_modules_code):
    name = module["name"]
    is_main = name == "main"

    if is_main:
        return f"""
Ты — ИИ-агент, который пишет ТОЛЬКО главный модуль Python-проекта (main.py).

СТРОГИЕ ПРАВИЛА ДЛЯ main.py:
1. Импортируй классы и функции из других модулей (из списка ниже).
2. Создавай объекты и вызывай их методы в функции main().
3. НЕ определяй классы.
4. НЕ определяй функции, кроме main().
5. НЕ дублируй код других модулей.

ДОСТУПНЫЕ МОДУЛИ ДЛЯ ИМПОРТА:
{list(interfaces.keys())}

ИНТЕРФЕЙСЫ (классы и методы других модулей):
{json.dumps(interfaces, indent=2, ensure_ascii=False)}

Техническое задание:
{tech_task}

Сгенерируй ТОЛЬКО main.py.
"""

    else:
        desc = module.get("description", "").strip()
        return f"""
Ты — ИИ-агент, который пишет библиотечный модуль Python.

Модуль: `{name}.py`
Описание: {desc}

СТРОГИЕ ПРАВИЛА:
1. Содержит ТОЛЬКО определения классов и функций, соответствующих описанию модуля.
2. НЕ создавай функцию main().
3. НЕ пиши if __name__ == "__main__".
4. НЕ используй print().
5. Если нужны функции из других модулей — импортируй их (абсолютные импорты).
6. НЕ дублируй код, который уже есть в других модулях.
7. Модуль должен содержать как минимум одну функцию или класс. Не оставляй модуль пустым!
8. Если в модуле не будет ни одной функции или класса, он будет бесполезен и удалён.

Код уже сгенерированных модулей (используй их, не дублируй):
{all_modules_code}

ДОСТУПНЫЕ ИНТЕРФЕЙСЫ:
{interfaces}

Техническое задание:
{tech_task}

Сгенерируй ТОЛЬКО код модуля `{name}.py`. Убедись, что в модуле есть полезный код, а не только импорты.
"""